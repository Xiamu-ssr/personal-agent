import { testRoot } from "./environment.mjs";
import fs from "node:fs";
import path from "node:path";
import test from "node:test";
import assert from "node:assert/strict";
import { once } from "node:events";
import { execFile } from "node:child_process";
import { promisify } from "node:util";
import WebSocket from "ws";
import { ConnectorManager, SECRET_MASK } from "../src/connectors.mjs";
import { DeviceHub } from "../src/devices.mjs";
import { startServer } from "../src/server.mjs";
import { config } from "../src/config.mjs";
import { writeJson } from "../src/store.mjs";
import { startFakeImap, FAKE_PASSWORD } from "./fake-imap.mjs";

const exec = promisify(execFile);
test("isolated HTTP CRUD/test/catalog via curl, safe errors, permissions and online/offline device deletion", async (t) => {
  const root = fs.mkdtempSync(path.join(testRoot, "http-")), imap = await startFakeImap(root);
  t.after(() => imap.close());
  let changed = 0;
  const connectors = new ConnectorManager({ root, definitions: [imap.connector], onChange: () => changed++ });
  const listeners = new Set();
  const bus = { on: (fn) => listeners.add(fn), emit: (ev) => listeners.forEach((fn) => fn(ev)) };
  const hub = new DeviceHub(), harness = { busy: false, running: new Map(), connectors };
  const server = startServer({ harness, hub, bus, log: () => {}, connectors, listen: { port: 0, host: "127.0.0.1" } });
  await once(server, "listening");
  t.after(async () => { server.closeAllConnections(); await new Promise((resolve) => server.close(resolve)); });
  const base = "http://127.0.0.1:" + server.address().port;
  async function curl(route, method = "GET", body, auth = true) {
    const args = ["--silent", "--show-error", "--max-time", "20", "--write-out", "\n%{http_code}", "--request", method];
    if (auth) args.push("--header", "Authorization: Bearer " + config.token);
    if (body !== undefined) args.push("--header", "Content-Type: application/json", "--data-binary", typeof body === "string" ? body : JSON.stringify(body));
    args.push(base + route);
    const { stdout } = await exec("curl", args);
    const lines = stdout.trimEnd().split("\n"), status = Number(lines.pop()), data = JSON.parse(lines.join("\n"));
    assert.equal(JSON.stringify(data).includes(FAKE_PASSWORD), false, "HTTP responses must not contain the fake credential");
    assert.equal(JSON.stringify(data).includes("bad-fake-password"), false);
    return { status, data };
  }
  assert.equal((await curl("/api/connectors", "GET", undefined, false)).status, 401);
  const initial = await curl("/api/connectors");
  assert.equal(initial.data.cloud.id, "cloud");
  assert.equal(initial.data.cloud.name, "云电脑");
  assert.equal(initial.data.cloud.kind, "cloud");
  assert.equal(initial.data.cloud.online, true);
  assert.equal("builtin" in initial.data.cloud, false);
  assert.deepEqual(initial.data.cloud.installed, []);
  assert.equal(initial.data.cloud.catalog[0].multiAccount, true);
  assert.equal(initial.data.cloud.catalog[0].fields.some((f) => f.type === "secret"), true);
  assert.equal(initial.data.cloud.catalog[0].status, "off");
  assert.equal("custom" in initial.data.cloud, false);
  const bad = await curl("/api/connectors/imap/accounts", "POST", { values: { ...imap.values(), password: "bad-fake-password" } });
  assert.equal(bad.status, 400);
  assert.match(bad.data.error, /授权码不对或没开 IMAP/);
  assert.equal(fs.existsSync(path.join(root, "system/connectors/imap/accounts.json")), false);
  assert.equal((await curl("/api/connectors/imap/accounts", "POST", { values: { preset: "qq" } })).status, 400);
  assert.equal((await curl("/api/connectors/imap/accounts", "POST", "not-json")).status, 400);
  assert.equal((await curl("/api/connectors/unknown/accounts", "POST", { values: imap.values() })).status, 404);
  const added = await curl("/api/connectors/imap/accounts", "POST", { values: imap.values() });
  assert.equal(added.status, 201);
  assert.equal(added.data.status, "ok");
  assert.equal("values" in added.data, false);
  const id = added.data.id, accountRoute = "/api/connectors/imap/accounts/" + id;
  const files = ["accounts.json", "state.json"].map((name) => path.join(root, "system/connectors/imap", name));
  for (const file of files) assert.equal(fs.statSync(file).mode & 0o777, 0o600);
  const installed = (await curl("/api/connectors")).data.cloud;
  assert.equal(installed.installed[0].name, "imap");
  assert.equal(installed.catalog.length, 0);
  assert.equal(installed.installed[0].accounts[0].id, id);
  assert.equal(installed.installed[0].accounts[0].values.password, SECRET_MASK);
  assert.equal("preset" in installed.installed[0].accounts[0].values, false);
  assert.equal((await curl(accountRoute, "PUT", { values: { password: SECRET_MASK, label: "Updated" } })).data.label, "Updated");
  assert.equal((await curl(accountRoute, "PUT", { values: { label: "Omitted secret" } })).status, 200);
  const before = fs.readFileSync(files[0], "utf8");
  assert.equal((await curl(accountRoute, "PUT", { values: { password: "bad-fake-password" } })).status, 400);
  assert.equal(fs.readFileSync(files[0], "utf8"), before);
  assert.equal((await curl(accountRoute + "/test", "POST")).status, 200);
  imap.failLogin = true;
  const retest = await curl(accountRoute + "/test", "POST");
  assert.equal(retest.status, 400);
  assert.equal(retest.data.status, "error");
  assert.match((await curl("/api/connectors")).data.cloud.installed[0].accounts[0].error, /授权码/);
  imap.failLogin = false;
  assert.equal((await curl(accountRoute + "/test", "POST")).data.status, "ok");
  const second = await curl("/api/connectors/imap/accounts", "POST", { values: imap.values("second@example.test") });
  assert.equal((await curl("/api/connectors")).data.cloud.installed[0].accounts.length, 2);
  assert.equal((await curl(accountRoute, "DELETE")).status, 200);
  assert.equal((await curl("/api/connectors")).data.cloud.installed[0].accounts.length, 1);
  assert.equal((await curl("/api/connectors/imap/accounts/" + second.data.id, "DELETE")).status, 200);
  assert.equal((await curl("/api/connectors")).data.cloud.catalog[0].name, "imap");
  assert.equal("imap" in connectors.mcpServers(), false);
  assert.equal(changed >= 8, true);
  for (const file of files) assert.equal(fs.statSync(file).mode & 0o777, 0o600);

  writeJson(path.join(config.system, "devices.json"), { offline: { id: "offline", name: "Fixture offline", lastSeen: 1 } });
  writeJson(hub.cursorFile("offline"), { fixture: { cursor: "dummy" } });
  hub.batches.set("fixture-batch", { deviceId: "offline", source: "fixture", cursor: "dummy" });
  assert.equal((await curl("/api/devices/offline", "DELETE")).status, 200);
  assert.equal(fs.existsSync(hub.cursorFile("offline")), false);
  assert.equal(hub.batches.has("fixture-batch"), false);
  assert.equal((await curl("/api/devices/offline", "DELETE")).status, 404);
  const ws = new WebSocket(base.replace("http:", "ws:") + "/ws?role=device", { headers: { Authorization: "Bearer " + config.token } });
  t.after(() => ws.terminate());
  await once(ws, "open");
  const registered = new Promise((resolve) => { hub.onChange = resolve; });
  ws.send(JSON.stringify({ t: "register", device: { id: "online", name: "Fixture online", kind: "mac", capabilities: [] } }));
  await registered;
  assert.equal((await curl("/api/devices/online", "DELETE")).status, 409);
  const disconnected = new Promise((resolve) => { hub.onChange = resolve; });
  ws.close();
  await disconnected;
  assert.equal((await curl("/api/devices/online", "DELETE")).status, 200);
});
