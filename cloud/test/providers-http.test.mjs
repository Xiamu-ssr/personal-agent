import "./environment.mjs";
import test from "node:test";
import assert from "node:assert/strict";
import { once } from "node:events";
import { setImmediate as tick } from "node:timers/promises";
import { WebSocket } from "ws";
import { Harness } from "../src/agent.mjs";
import { DeviceHub } from "../src/devices.mjs";
import { startServer } from "../src/server.mjs";
import { config } from "../src/config.mjs";
import { putAppSettings, DEFAULT_SETTINGS } from "../src/app-settings.mjs";
import { queryFixture } from "./query-fixture.mjs";
import { fakeAnthropic } from "./fake-anthropic.mjs";

test("provider HTTP CRUD follows the shared contract, broadcasts settings and never returns or logs keys", async (t) => {
  const key = "fake-http-provider-1234", nextKey = "fake-http-provider-5678", badKey = "fake-http-provider-badkey";
  const events = [], logs = [], responses = [], sockets = [], listeners = new Set(), calls = [], hub = new DeviceHub();
  const bus = { on: (fn) => listeners.add(fn), emit: (ev) => { events.push(ev); for (const fn of listeners) fn(ev); } };
  const api = await fakeAnthropic((_body, _i, { headers }) => headers.authorization.endsWith(badKey) ? { error: "invalid " + badKey, status: 401 } : {});
  putAppSettings(config.root, { ...DEFAULT_SETTINGS });
  const h = new Harness({ hub, bus, log: (...args) => logs.push(args), queryFactory: queryFixture(calls) }); h.startMain();
  const server = startServer({ harness: h, hub, bus, log: (...args) => logs.push(args), listen: { host: "127.0.0.1", port: 0 } }); await once(server, "listening");
  const url = "http://127.0.0.1:" + server.address().port;
  const ws = new WebSocket(url.replace("http:", "ws:") + "/ws", { headers: { authorization: "Bearer " + config.token } });
  ws.on("message", (data) => sockets.push(JSON.parse(data))); await once(ws, "open");
  t.after(async () => { ws.terminate(); server.closeSockets(); server.closeAllConnections(); await new Promise((resolve) => server.close(resolve)); await h.close(); await api.close(); });
  const req = async (route, method = "GET", body, auth = true) => {
    const response = await fetch(url + route, { method, headers: { "content-type": "application/json", ...(auth && { authorization: "Bearer " + config.token }) }, ...(body && { body: JSON.stringify(body) }) });
    const value = { status: response.status, body: await response.json() }; responses.push(value); return value;
  };
  const data = { name: "我的测试服务", baseUrl: api.url + "/", apiKey: key, models: [{ id: "custom-1", name: "自定义一" }, { id: "custom-2", name: "自定义二" }] };
  assert.equal((await req("/api/providers", "POST", data, false)).status, 401);
  assert.equal((await req("/api/providers/test", "POST", { baseUrl: api.url, apiKey: key, model: "custom-1" })).body.ok, true);
  assert.equal((await req("/api/settings")).body.providers.length, 1, "testing does not save");
  const added = await req("/api/providers", "POST", data); assert.equal(added.status, 200);
  const provider = added.body.provider, route = "/api/providers/" + provider.id;
  assert.equal(provider.keyHint, "1234"); assert.deepEqual(provider.models, data.models); assert.equal(provider.baseUrl, api.url);
  assert.equal((await req(route, "PATCH", { apiKey: "", name: "改名" })).body.provider.keyHint, "1234");
  assert.equal((await req(route, "PATCH", { apiKey: nextKey })).body.provider.keyHint, "5678");
  assert.equal((await req("/api/providers", "POST", { ...data, name: key, apiKey: "fake-other-service-key" })).status, 400);
  const selected = { provider: provider.id, id: "custom-2" };
  assert.deepEqual((await req("/api/settings", "PUT", { model: selected })).body.model, selected);
  assert.deepEqual(await req(route, "DELETE"), { status: 409, body: { error: "先换到别的模型" } });
  assert.equal((await req(route, "PATCH", { models: [{ id: "custom-1", name: "一" }] })).status, 409);
  assert.equal((await req("/api/settings", "PUT", { model: "custom-2" })).status, 400);
  const failed = await req("/api/providers/test", "POST", { baseUrl: api.url, apiKey: badKey, model: "custom-1" });
  assert.equal(failed.status, 400); assert.match(failed.body.error, /^HTTP 401：invalid ••••$/);
  h.log("provider diagnostic", key, nextKey, badKey);
  await h.send("检查脱敏"); calls.at(-1).emit({ type: "assistant", message: { content: [{ type: "text", text: "internal " + nextKey }] } });
  calls.at(-1).emit({ type: "result", subtype: "success" }); await tick();
  const history = await req("/api/activities/" + h.main.activityId + "/history"); assert.match(JSON.stringify(history), /internal ••••/);
  await req("/api/history"); await req("/api/activities"); await req("/api/state");
  await req("/api/settings", "PUT", { model: DEFAULT_SETTINGS.model }); assert.equal((await req(route, "DELETE")).body.ok, true);
  await tick();
  assert.ok(events.some((ev) => ev.t === "settings" && ev.providers?.some((p) => p.id === provider.id)));
  assert.ok(sockets.some((ev) => ev.t === "settings" && ev.model.provider === provider.id));
  for (const [label, values] of Object.entries({ responses, events, sockets, logs })) for (const [index, value] of values.entries()) for (const secret of [key, nextKey, badKey]) assert.equal(JSON.stringify(value).includes(secret), false, label + " item " + index + " contains a provider key");
  assert.equal((await req("/api/settings")).body.providers.length, 1);
});
